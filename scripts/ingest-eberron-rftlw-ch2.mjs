function structuredSourceContent(source, title) {
  const normalizedSource = sourceText(source)
    .replace(/^#\s+[^\n]+\r?\n+/, "")
    .replace(/^(\*\*.+\*\*)\r?\n(.+\*\*)\r?\n\r?\n\*\*——(.+)\*\*/m, (_match, first, second, author) => `> [!QUOTE]- ${author.trim()}\n>\n> ${first.replaceAll("**", "")}\n> ${second.replaceAll("**", "")}`)
    .replace(/^\*\*([^*\r\n]+)\*\*\r?\n(?:\*\*)?([^*\r\n]+)\*\*\r?\n(?:[ \t]*\r?\n)*\* \* \*\r?\n(?:[ \t]*\r?\n)*#\s+([^\r\n]+)$/gm, "# $1$2\n# $3");
  const lines = normalizedSource.split(/\r?\n/);
  const result = [];
  let inReport = false;
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (/^\*\*(?:首都|特色|前特色)：\*\*/.test(line)) {
      inReport = false;
      continue;
    }
    if (/^\* \* \*$/.test(line.trim())) continue;
    if (/^#\s+/.test(line)) {
      const outlet = line.replace(/^#\s+/, "").trim();
      if (outlet === "第二章") continue;
      const nextHeading = lines.slice(index + 1).find((candidate) => /^#\s+/.test(candidate));
      if (nextHeading) {
        result.push(`> [!QUOTE]- ${outlet}：${nextHeading.replace(/^#\s+/, "").trim()}`);
        inReport = true;
        continue;
      }
      if (inReport || lines.slice(0, index).some((candidate) => /^#\s+/.test(candidate))) continue;
      result.push(`> [!QUOTE]- ${outlet}`);
      inReport = true;
      continue;
    }
    if (/^##\s+/.test(line)) {
      inReport = false;
      result.push(`### ${line.replace(/^##\s+/, "")}`);
      continue;
    }
    if (/^###\s+/.test(line)) {
      inReport = false;
      result.push(line);
      continue;
    }
    if (inReport && !line.trim()) {
      if (result[result.length - 1] !== ">") result.push(">");
      continue;
    }
    result.push(inReport ? `> ${line}` : line);
  }
  const content = result.join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return content || `本條目詳細內容請參照來源「${title}」。`;
}

function sourceFeatures(source) {
  const text = sourceText(source);
  const capital = text.match(/^\*\*首都：\*\*\s*(.+)$/m)?.[1]?.trim() ?? text.match(/^首都：\s*(.+)$/m)?.[1]?.trim();
  const features = text.match(/^\*\*(?:前)?特色：\*\*\s*(.+)$/m)?.[1]?.trim() ?? text.match(/^(?:前)?特色：\s*(.+)$/m)?.[1]?.trim();
  const headings = [...text.matchAll(/^###\s+(.+)$/gm)].map((match) => match[1].replace(/\s+[A-Za-z][A-Za-z'’\- ]+$/, "").trim());
  const citySection = text.match(/### (?:城市與地標|顯要地點)[\s\S]*?(?=\n### |$)/);
  const sites = citySection
    ? [...citySection[0].matchAll(/^\*\*([^*]+?)\*\*/gm)]
      .map((match) => match[1].replace(/\s+[A-Z][A-Za-z'’\- ]*[。.]?$/, "").trim())
      .filter((name) => name && !name.includes("是"))
    : [];
  return { capital, features, headings, sites };
}

function sourceStructure(source) {
  const text = sourceText(source);
  const sections = [...text.matchAll(/^###\s+(.+)\n([\s\S]*?)(?=^###\s+|$)/gm)].map((match) => {
    const heading = match[1].replace(/\s+[A-Za-z][A-Za-z'’\- ]+$/, "").trim();
    const boldTopics = [...match[2].matchAll(/^\s*(?:-\s*)?\*\*([^*]+?)\*\*/gm)]
      .map((topic) => topic[1].replace(/\s+[A-Za-z][A-Za-z'’\- ]*[。.]?$/, "").trim())
      .filter((topic) => topic && !topic.includes("是"));
    return { heading, boldTopics };
  });
  return sections.filter((section) => section.boldTopics.length > 0);
}

